// 语法/主题资产生成器（node，无第三方依赖）——issue #220 WP4 高亮换代。
//
// 职责：从本仓 `node_modules/@wooorm/starry-night` 里把 **TS 基线实际在用的**
// 14 份 TextMate 语法与 github 类名主题表**机械化**导出为本 crate 的资产：
//   - assets/grammars/<scope>.json   语法原文（tmLanguage JSON，逐字节语义等价）
//   - assets/grammars/SOURCES.md     每份语法的来源与许可证（vendored 必须注明）
//   - assets/starry-theme.json       starry-night 的 scope 选择器 → pl-* 类名映射
//                                    （含 sorted classes / grandparents / transparent）
// 运行（仓库根）：
//   node src-tauri/pylon-markdown/gen/generate-assets.mjs
// 产物是提交进仓的生成物；starry-night 升级时重跑本脚本并复核 parity。
//
// 为什么从 node_modules 导出：parity 的比对面是「TS 基线现场解析」，而 TS 基线
// 用的语法/主题正是这个包里这份。从源头导出（而不是手抄）保证两侧逐字节同源，
// 升级 TS 依赖时 Rust 侧资产可用同一条命令再生成。

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(path.join(process.cwd(), 'package.json'))
// exports 映射不含 package.json，改从包主入口 index.js 反推包目录。
const starryDir = path.dirname(require.resolve('@wooorm/starry-night'))

// 与 TS 基线 codeHighlight.ts 的 GRAMMAR_LOADERS 同表（14 个 scope）。
const SCOPES = [
  'source.js', 'source.ts', 'source.tsx', 'source.python', 'source.rust',
  'source.go', 'source.java', 'source.c', 'source.c++', 'source.css',
  'source.json', 'source.yaml', 'source.shell', 'text.html.basic',
]

const outRoot = path.resolve('src-tauri/pylon-markdown/assets')
const grammarDir = path.join(outRoot, 'grammars')
mkdirSync(grammarDir, { recursive: true })

// ── 1) 语法导出：lang/<scope>.js 是 `const grammar = {...}; export default` 的
// ESM 模块，动态 import 拿到原始 JSON 对象后原样落盘（不重排键序也无妨，Rust 侧
// 按 JSON 语义读取）。文件头注释含来源与许可证，抽取进 SOURCES.md。
const sources = [
  '# 语法资产来源（generated by gen/generate-assets.mjs，勿手改）', '',
  '来自 npm 包 `@wooorm/starry-night` 的 `lang/` 目录，JSON 为其 ESM 模块内', 'grammar 对象的原样导出。各语法原始出处与许可证如下：', '',
]
for (const scope of SCOPES) {
  const file = path.join(starryDir, 'lang', `${scope}.js`)
  const src = readFileSync(file, 'utf8')
  const mod = await import(`file:///${file.replaceAll('\\', '/')}`)
  const grammar = mod.default
  if (!grammar || typeof grammar.scopeName !== 'string' || grammar.scopeName !== scope) {
    throw new Error(`${scope}: 导出的语法 scopeName 与文件名不符`)
  }
  writeFileSync(path.join(grammarDir, `${scope}.json`), JSON.stringify(grammar))
  // 头注释形如：
  //   // This is a TextMate grammar distributed by `starry-night`.
  //   // This grammar is developed at
  //   // <https://...>
  //   // and licensed `mit`.
  const origin = src.match(/developed at\n\/\/ <([^>]+)>/)?.[1] ?? '（模块头注释未声明出处）'
  const license = src.match(/and licensed `([^`]+)`/)?.[1] ?? '（未声明）'
  sources.push(`- \`${scope}.json\` — 出自 ${origin}，许可证 ${license}`)
}
writeFileSync(path.join(grammarDir, 'SOURCES.md'), `${sources.join('\n')}\n`)

// ── 2) 主题表导出：starry-night 的类名体系全在 lib/theme.js——`scopeToClassGithub`
// 是「scope 选择器 → github css 类名」的对照表，`theme` 是把它编码成颜色的
// vscode-textmate 主题（颜色序号 = sorted classes 下标）。这里把三个出口
// （theme / classes / grandparents / transparent）原样序列化，Rust 侧的
// theme.rs 按 vscode-textmate 的匹配算法消费它，不做任何语义改写。
const themeMod = await import(`file:///${path.join(starryDir, 'lib', 'theme.js').replaceAll('\\', '/')}`)
const payload = {
  // 与 starry-night 版本绑定的快照；升级依赖后须重跑本脚本。
  generator: 'gen/generate-assets.mjs from @wooorm/starry-night/lib/theme.js',
  classes: themeMod.classes,
  grandparents: themeMod.grandparents,
  transparent: themeMod.transparent,
  // theme.settings 里每条 {scope, settings:{field: color}}；field ∈ fontStyle/foreground/background。
  settings: themeMod.theme.settings,
}
writeFileSync(path.join(outRoot, 'starry-theme.json'), JSON.stringify(payload))

console.log(`generate-assets: ${SCOPES.length} grammars + theme → ${outRoot}`)
